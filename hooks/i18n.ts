// pulse-pane v1.1.0: every string the pane shows, in ten languages.
//
// `Strings` is the contract: a language that misses a key, or a function with the
// wrong arguments, does not type-check. Keep labels short; the drawing clips what
// does not fit, but a clipped tool-lane or stat label reads worse than a short one.
import type { Phase, ToolKind } from '../types'

export const LANGS = ['en', 'ar', 'es', 'fr', 'de', 'pt', 'ru', 'zh', 'ja', 'hi'] as const
export type Lang = (typeof LANGS)[number]
export const DEFAULT_LANG: Lang = 'en'

export const isLang = (value: unknown): value is Lang =>
  typeof value === 'string' && (LANGS as readonly string[]).includes(value)

export type Strings = {
  /** The language's own name, as `/pulse` lists it. */
  name: string
  dir: 'ltr' | 'rtl'
  kind: Record<ToolKind, string>
  phase: Record<Phase, { label: string; sub: string }>
  pipeline: string
  you: string
  claude: string
  tools: string
  running: (n: number) => string
  noneRunning: string
  timeline: string
  noCalls: string
  errorWord: string
  context: string
  cost: string
  costStale: string
  staleShort: string
  output: string
  turns: string
  recentTurns: string
  noTurns: string
  toolMix: string
  calls: string
  topFiles: string
  noFiles: string
  subagents: string
  noAgents: string
  agentCount: (live: number, total: number) => string
  steps: (n: number) => string
  headerLine: (thinking: string, writing: string, contextPct: number) => string
  terminalLine: (contextPct: number, tools: number, output: string) => string
  alt: (phase: string, calls: number, contextPct: number) => string
  commandDescription: string
  opened: string
  languageSet: string
  languageUnknown: (given: string, codes: string) => string
  languageNotSettable: string
}

